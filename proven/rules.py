"""Domain rules: deterministic checks on recorded findings (the reviewer's first layer).

Rules live in each pack's rules.yaml and are written by domain experts, not generated by a model.
The general pack's rules (statistics, percentages) apply to every pack. A rule fires when its
trigger words appear in a finding's claim, then checks one of:

- the number right after the trigger word    ("径流系数为 1.3" -> 1.3 must lie in 0-1)
- a named fact found in the claim, the evidence, or other findings of the run
  (p_value, correlation, sample_size, return_period, cs_cv, or any labelled value)
- the ratio of two facts                     (return period / sample length <= 5)
- whether required wording is present        (水文年 / 日历年 must be stated)

See docs/domain-rules-template.md for the file format.
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Iterable

import yaml

from .findings import extract_numbers

NUM = r"[-−]?\d+(?:,\d{3})*(?:\.\d+)?(?:[eE][-+]?\d+)?"
_CMP = r"(?P<cmp><=|>=|≤|≥|<|＜|>|＞|≈|=|＝|:|：)"

# Built-in facts. Each pattern captures `num` (and optionally `cmp`); later patterns are weaker evidence.
# A pattern may carry a converter, e.g. exceedance frequency 1% -> return period 100 years.
_CN_RETURN = {"十": 10, "二十": 20, "五十": 50, "百": 100, "二百": 200, "五百": 500, "千": 1000, "万": 10000}
FACTS: dict[str, list[tuple[str, Any]]] = {
    "p_value": [
        (rf"(?<![A-Za-z])[pP](?:[\s_-]?values?)?\s*(?:值)?\s*{_CMP}\s*(?P<num>{NUM})", None),
        (rf"[pP]\s*值\s*(?:为|是|约为|约)\s*(?P<cmp><|＜|≤)?\s*(?P<num>{NUM})", None),
    ],
    "correlation": [
        (rf"(?<![A-Za-z])(?:[rRρ]|rho)(?![A-Za-z²0-9_])\s*{_CMP}\s*(?P<num>{NUM})", None),
        (rf"相关系数[^。；;\n\d]{{0,8}}?(?P<num>{NUM})", None),
    ],
    "sample_size": [
        (r"(?:样本量|样本数|样本长度|样本容量|序列长度|系列长度|资料长度|资料年限|记录长度|sample size)\s*(?:为|是|共|仅|只有|=|＝|:|：)?\s*(?P<num>\d+)", None),
        (r"(?<![A-Za-z_])[nN]\s*[=＝:：]\s*(?P<num>\d+)", None),
        (r"样本\s*(?:为|是|共|仅)?\s*(?P<num>\d+)\s*(?:年|个)", None),
        (r"(?:共|仅|只有)\s*(?P<num>\d+)\s*(?:年|个)", None),
        (r"(?P<num>\d+)\s*(?:年|个)(?:的)?(?:实测|观测)?(?:资料|数据|序列|系列|样本|记录|年最大值|洪峰)", None),
        (r"(?<!\d)(?P<a>(?:19|20)\d{2})\s*[-–—~～至到]\s*(?P<num>(?:19|20)\d{2})(?!\d)", "span"),
    ],
    "return_period": [
        (r"(?P<num>\d+(?:\.\d+)?)\s*年一遇", None),
        (r"(?P<cn>十|二十|五十|百|二百|五百|千|万)年一遇", "cn"),
        (r"重现期\s*(?:为|是|=|＝|:|：)?\s*(?P<num>\d+(?:\.\d+)?)\s*年?", None),
        (r"(?<![A-Za-z])T\s*=\s*(?P<num>\d+(?:\.\d+)?)", None),
        (r"(?:频率|(?<![A-Za-z])P)\s*(?:为|=|＝|:|：)?\s*(?P<num>\d+(?:\.\d+)?)\s*[%％]", "freq"),
    ],
    "cs_cv": [
        (rf"Cs\s*/\s*Cv\s*(?:为|是|约为|=|＝|:|：|≈)?\s*(?P<num>{NUM})", None),
    ],
}

_STOP = "。；;！!？?\n"
# Between a quantity and its number: no list separators, comparisons, ordinals, or another quantity
# ("径流系数与干旱指数的相关系数为 -0.75": -0.75 belongs to 相关系数, not 径流系数).
_GAP_FORBIDDEN = re.compile(r"[与和及跟、,，]|超过|大于|小于|低于|高于|不足|不到|以上|以下|接近|前|第|[<>≤≥＜＞]"
                            r"|系数|指数|比例|比值|斜率|相关|差值|变化")
_COUNT_SUFFIX = re.compile(r"^\s*(?:个|名|条|座|站|年|月|日|天|次|位|家|类|项|件|倍)")
_PAREN = re.compile(r"[（(][^）)]{0,16}[）)]")

CHECK_KEYS = {"min", "max", "abs_min", "abs_max", "percent", "skip_percent", "fact", "ratio", "mention_any", "in",
              "if_missing"}
SCOPES = {"claim", "evidence", "run"}


@dataclass
class Rule:
    id: str
    name: str
    type: str  # range | condition | consistency (documentation and grouping only)
    severity: str  # error | warning
    applies_when: list[str]
    check: dict[str, Any]
    message: str
    basis: str = ""
    unless_mention: list[str] = field(default_factory=list)
    source: str = ""  # pack id the rule comes from

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class Issue:
    finding_id: str
    severity: str  # error | warning
    message: str
    detail: str = ""
    rule_id: str = ""  # empty for issues raised by the model reviewer
    name: str = ""
    basis: str = ""
    source: str = "rule"  # rule | llm
    suggestion: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class Evidence:
    """What a rule can look at for one finding."""

    claim: str
    evidence: str = ""  # cited cell outputs and code, or document text
    run: str = ""  # claims of the other findings in the run


class RuleError(ValueError):
    pass


class RuleSet:
    def __init__(self, rules: list[Rule], review_points: list[str] | None = None):
        self.rules = rules
        self.review_points = review_points or []

    def __len__(self) -> int:
        return len(self.rules)

    def to_dict(self) -> dict[str, Any]:
        return {"rules": [r.to_dict() for r in self.rules], "review_points": self.review_points}

    def check(self, finding_id: str, ev: Evidence) -> list[Issue]:
        issues = []
        for rule in self.rules:
            detail = evaluate(rule, ev)
            if detail is None:
                continue
            severity, text = detail
            text = text.strip()
            issues.append(Issue(finding_id=finding_id, severity=severity, message=rule.message, detail=text,
                                rule_id=rule.id, name=rule.name, basis=rule.basis))
        return issues


# ---------------------------------------------------------------------- loading


def load_rules(pack_dir: Path, general_dir: Path | None = None) -> RuleSet:
    """The pack's rules, preceded by the general rules (a pack rule with the same id wins)."""
    files = []
    if general_dir is not None and general_dir.resolve() != pack_dir.resolve():
        files.append(general_dir / "rules.yaml")
    files.append(pack_dir / "rules.yaml")
    by_id: dict[str, Rule] = {}
    points: list[str] = []
    for f in files:
        if not f.exists():
            continue
        rules, pts = parse_rules(f.read_text(encoding="utf-8"), source=f.parent.name)
        for r in rules:
            by_id[r.id] = r
        points += pts
    return RuleSet(list(by_id.values()), points)


def parse_rules(text: str, source: str = "") -> tuple[list[Rule], list[str]]:
    data = yaml.safe_load(text) or {}
    out = []
    for i, raw in enumerate(data.get("rules") or [], 1):
        rid = raw.get("id") or f"#{i}"
        where = f"{source}/rules.yaml 规则 {rid}"
        for key in ("id", "name", "applies_when", "check", "message"):
            if not raw.get(key):
                raise RuleError(f"{where}：缺少字段 {key}")
        check = dict(raw["check"])
        unknown = set(check) - CHECK_KEYS
        if unknown:
            raise RuleError(f"{where}：check 中有不认识的字段 {sorted(unknown)}，可用字段：{sorted(CHECK_KEYS)}")
        fact = check.get("fact")
        names = [fact] if fact else []
        if check.get("ratio"):
            names += [check["ratio"].get("of"), check["ratio"].get("to")]
        for name in names:
            if isinstance(name, str) and name not in FACTS:
                raise RuleError(f"{where}：未知的 fact {name}，内置的有 {sorted(FACTS)}，也可以写 {{labels: [...]}}")
            if isinstance(name, dict) and not name.get("labels"):
                raise RuleError(f"{where}：自定义 fact 需要 labels")
        scopes = check.get("in", ["claim"])
        scopes = [scopes] if isinstance(scopes, str) else scopes
        if set(scopes) - SCOPES:
            raise RuleError(f"{where}：in 只能取 {sorted(SCOPES)}")
        severity = raw.get("severity", "warning")
        if severity not in ("error", "warning"):
            raise RuleError(f"{where}：severity 只能是 error 或 warning")
        triggers = raw["applies_when"]
        out.append(
            Rule(
                id=str(raw["id"]),
                name=raw["name"],
                type=raw.get("type", "condition"),
                severity=severity,
                applies_when=[triggers] if isinstance(triggers, str) else list(triggers),
                check=check,
                message=raw["message"].strip(),
                basis=(raw.get("basis") or "").strip(),
                unless_mention=list(raw.get("unless_mention") or []),
                source=source,
            )
        )
    return out, [str(p) for p in data.get("review_points") or []]


# ---------------------------------------------------------------------- evaluation


def _has(text: str, term: str) -> bool:
    if term.startswith("re:"):
        return re.search(term[3:], text, re.I) is not None
    return term.lower() in text.lower()


def _triggers(rule: Rule, claim: str) -> list[re.Match]:
    return [m for t in rule.applies_when for m in re.finditer(re.escape(t), claim, re.I)]


def evaluate(rule: Rule, ev: Evidence) -> tuple[str, str] | None:
    """None when the rule passes or does not apply, else (severity, what was found)."""
    hits = _triggers(rule, ev.claim)
    if not hits:
        return None
    if any(_has(ev.claim, t) for t in rule.unless_mention):
        return None
    c = rule.check
    scopes = c.get("in", ["claim"])
    scopes = [scopes] if isinstance(scopes, str) else scopes

    if "mention_any" in c:
        text = _scoped(ev, scopes)
        for t in rule.applies_when:  # "同比" must not satisfy its own "比"
            text = re.sub(re.escape(t), " ", text, flags=re.I)
        if any(_has(text, t) for t in c["mention_any"]):
            return None
        words = [t for t in c["mention_any"] if not t.startswith("re:")]
        more = len(c["mention_any"]) > 6 or len(words) < len(c["mention_any"])
        return rule.severity, "未提到：" + "、".join(words[:6]) + ("等" if more else "")

    fact_scopes = scopes if "in" in c else ["claim", "evidence", "run"]
    if "ratio" in c:
        r = c["ratio"]
        a, b = find_fact(r["of"], ev, fact_scopes), find_fact(r["to"], ev, fact_scopes)
        if not a or not b:
            return _missing(rule, f"未找到 {_fact_name(r['of'] if not a else r['to'])}")
        va, vb = max(v for v, _ in a), min(v for v, _ in b)
        if vb <= 0:
            return None
        ratio = va / vb
        if "max" in r and ratio > r["max"]:
            return rule.severity, f"{_fact_name(r['of'])} {_fmt(va)} 是 {_fact_name(r['to'])} {_fmt(vb)} 的 {ratio:.1f} 倍（上限 {r['max']} 倍）"
        return None

    if "fact" in c:
        values = find_fact(c["fact"], ev, fact_scopes)
        name = _fact_name(c["fact"])
        if not values:
            return _missing(rule, f"未找到{name}")
        bad = [(v, cmp) for v, cmp in values if not _within(v, cmp, c)]
        if not bad:
            return None
        if len(bad) < len(values):
            return "warning", f"找到多个{name}（{'、'.join(_fmt(v) for v, _ in values[:6])}），其中部分不满足要求，请在结论中写明对应的数值"
        return rule.severity, f"{name}为 {'、'.join(_fmt(v, cmp) for v, cmp in bad[:6])}，要求{_bounds(c)}"

    # Range on the numbers right after each trigger word.
    values = [v for m in hits for v in _values_after(ev.claim, m.end(), c)]
    bad = [v for v in values if not _within(v, None, c)]
    if bad:
        return rule.severity, f"取到的值 {'、'.join(_fmt(v) for v in bad[:6])}，要求{_bounds(c)}"
    return None


def _missing(rule: Rule, text: str) -> tuple[str, str] | None:
    mode = rule.check.get("if_missing", "pass")
    if mode == "pass":
        return None
    return ("error" if mode == "error" else "warning"), text


def _scoped(ev: Evidence, scopes: Iterable[str]) -> str:
    return "\n".join(getattr(ev, s) for s in scopes if getattr(ev, s))


def _within(v: float, cmp: str | None, c: dict[str, Any]) -> bool:
    # "p < 0.05" states an upper bound: fine when the bound itself meets the maximum.
    if "max" in c and v > c["max"] + 1e-12:
        return False
    if "min" in c and v < c["min"] - 1e-12 and cmp not in ("<", "＜", "<=", "≤"):
        return False
    if "abs_min" in c and abs(v) < c["abs_min"] - 1e-12:
        return False
    if "abs_max" in c and abs(v) > c["abs_max"] + 1e-12:
        return False
    return True


def _bounds(c: dict[str, Any]) -> str:
    unit = "%" if c.get("percent") else ""
    parts = []
    if "min" in c and "max" in c:
        parts.append(f"在 {c['min']}{unit}–{c['max']}{unit} 之间")
    elif "min" in c:
        parts.append(f"不小于 {c['min']}{unit}")
    elif "max" in c:
        parts.append(f"不大于 {c['max']}{unit}")
    if "abs_min" in c:
        parts.append(f"绝对值不小于 {c['abs_min']}")
    if "abs_max" in c:
        parts.append(f"绝对值不大于 {c['abs_max']}")
    return "，".join(parts)


def _fmt(v: float, cmp: str | None = None) -> str:
    s = f"{v:.4g}" if abs(v) < 1e5 else f"{v:,.0f}"
    return (cmp if cmp in ("<", "＜", "≤", "<=") else "") + s


def _fact_name(fact: Any) -> str:
    names = {"p_value": " p 值", "correlation": "相关系数", "sample_size": "样本长度", "return_period": "重现期", "cs_cv": " Cs/Cv"}
    if isinstance(fact, dict):
        return fact.get("name") or fact["labels"][0]
    return names.get(fact, fact)


def _values_after(claim: str, pos: int, c: dict[str, Any]) -> list[float]:
    """Numbers that state the value of the quantity named just before `pos`."""
    rest = _PAREN.sub(lambda m: " " * len(m.group(0)), claim[pos:])
    m = re.match(rf"(?P<gap>[^{_STOP}\d−-]{{0,12}}?)(?P<num>{NUM})\s*(?P<pct>%|％)?", rest)
    if not m or _GAP_FORBIDDEN.search(m.group("gap")) or _COUNT_SUFFIX.match(rest[m.end("num"):]):
        return []
    found = [(m.group("num"), m.group("pct"))]
    if "分别" in m.group("gap"):
        nxt = re.compile(rf"\s*(?:[、，,和及与]\s*)+(?P<num>{NUM})\s*(?P<pct>%|％)?")
        pos = m.end()
        while mm := nxt.match(rest, pos):
            found.append((mm.group("num"), mm.group("pct")))
            pos = mm.end()
    out = []
    for raw, pct in found:
        nums = extract_numbers(raw + (pct or ""), skip_trivial=False)
        if not nums:
            continue
        v = nums[0].value
        if pct:
            if c.get("skip_percent"):
                continue
            if not c.get("percent"):
                v /= 100
        elif c.get("percent") and abs(v) <= 1:
            v *= 100
        out.append(v)
    return out


def find_fact(fact: Any, ev: Evidence, scopes: Iterable[str]) -> list[tuple[float, str | None]]:
    """Values of a fact from the first scope (claim, then evidence, then other findings) that has any."""
    patterns = _patterns(fact)
    for scope in scopes:
        text = getattr(ev, scope)
        if not text:
            continue
        for pat, conv in patterns:  # strongest pattern that matches wins within a scope
            vals = []
            for m in re.finditer(pat, text, re.I if conv != "cn" else 0):
                v = _convert(m, conv)
                if v is not None:
                    cmp = m.groupdict().get("cmp")
                    vals.append((v, cmp if cmp in ("<", "＜", "≤", "<=", ">", "＞", "≥", ">=") else None))
            if vals:
                return list(dict.fromkeys(vals))
    return []


def _patterns(fact: Any) -> list[tuple[str, Any]]:
    if isinstance(fact, dict):
        labels = "|".join(re.escape(x) for x in fact["labels"])
        return [(rf"(?:{labels})\s*(?:[（(][^）)]{{0,10}}[）)])?\s*(?:值)?\s*(?:为|是|约为|约|达到|达|=|＝|:|：|≈)?\s*(?P<num>{NUM})", None)]
    return FACTS[fact]


def _convert(m: re.Match, conv: Any) -> float | None:
    if conv == "cn":
        return float(_CN_RETURN[m.group("cn")])
    v = float(m.group("num").replace(",", "").replace("−", "-"))
    if conv == "freq":
        return 100 / v if v > 0 else None
    if conv == "span":
        a = int(m.group("a"))
        return float(v - a + 1) if v > a else None
    return v
